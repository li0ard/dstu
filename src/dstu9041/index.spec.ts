import { describe, test, expect } from "bun:test";
import { dstu9041_256, dstu9041_512 } from ".";
import { hexToBytes, type TRet } from "@noble/curves/utils.js";

const performTest = (
    cipher: typeof dstu9041_256 | typeof dstu9041_512,
    privateKey: Uint8Array,
    message: Uint8Array,
    rand: Uint8Array,
    expectedPk: Uint8Array,
    expectedCt: Uint8Array,
) => {
    const publicKey = cipher.getPublicKey(privateKey);
    expect(publicKey).toStrictEqual(expectedPk as TRet<Uint8Array>);

    const encrypted = cipher.encrypt(message, publicKey, rand);
    expect(encrypted).toStrictEqual(expectedCt as TRet<Uint8Array>);

    expect(cipher.decrypt(encrypted, privateKey)).toStrictEqual(message as TRet<Uint8Array>);

    // Random keypair
    const keypair = cipher.keygen();
    expect(cipher.decrypt(cipher.encrypt(message, keypair.publicKey), keypair.secretKey)).toStrictEqual(message as TRet<Uint8Array>);
}

